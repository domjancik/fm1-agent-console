"""fixtures/device/led-v2.json (docs/ui-v3.md sections 9.9 and 10.8, written by the simulator's gen-led-v2.ts) as a C header for
led_test.c, so the firmware's LED timelines are checked against the same numbers as the simulator's.

  python3 tests/console/gen_led_v2.py ../fixtures/device/led-v2.json build/console/led_v2.h"""
import json
import sys

STATES = {
    "empty": "FM1C_S_EMPTY", "disconnected": "FM1C_S_DISCONNECTED", "idle": "FM1C_S_IDLE", "working": "FM1C_S_WORKING",
    "waiting_input": "FM1C_S_WAITING_INPUT", "approval_required": "FM1C_S_APPROVAL",
    "completed_unread": "FM1C_S_DONE_UNREAD", "completed_read": "FM1C_S_DONE_READ", "failed": "FM1C_S_FAILED",
    "unknown": "FM1C_S_UNKNOWN",
}
VIEWS = {"sessions": "FM1C_VIEW_SESSIONS", "tasks": "FM1C_VIEW_TASKS", "inbox": "FM1C_VIEW_INBOX", "voice": "FM1C_VIEW_VOICE",
         "confirm": "FM1C_VIEW_CONFIRM", "detail": "FM1C_VIEW_DETAIL", "settings": "FM1C_VIEW_SETTINGS"}
VOICES = {"ready": "FM1C_V_READY", "recording": "FM1C_V_RECORDING", "transcribing": "FM1C_V_TRANSCRIBING",
          "reviewing": "FM1C_V_REVIEWING", "submitting": "FM1C_V_SUBMITTING", "delivered": "FM1C_V_DELIVERED",
          "cancelled": "FM1C_V_CANCELLED", "failed": "FM1C_V_FAILED", "target_unavailable": "FM1C_V_NO_TARGET"}
LEVELS = {"off": "FM1C_LED_OFF", "glow": "FM1C_LED_GLOW", "full": "FM1C_LED_FULL", "breath": "FM1C_LED_BACK"}


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    src, out = sys.argv[1], sys.argv[2]
    d = json.load(open(src, encoding="utf-8"))
    lines = ["/* generated by tests/console/gen_led_v2.py from fixtures/device/led-v2.json: do not edit */",
             "#pragma once", "#include <stdint.h>",
             "typedef struct { uint32_t ms; uint8_t level; } led2_sample;",
             "typedef struct { const char *name; uint8_t state, selected, stale; uint8_t n; led2_sample s[40]; } led2_key;",
             "typedef struct { const char *name; uint8_t n; led2_sample s[40]; } led2_button;"]
    bn = d["breathNs"]
    lines.append(f"static const uint16_t LED2_BREATH_NS[{len(bn)}] = {{{', '.join(str(x) for x in bn)}}};")
    lines.append(f"#define LED2_BREATH_STEP_MS {d['breath']['stepMs']}u")
    lines.append(f"#define LED2_BREATH_PERIOD_MS {d['breath']['periodMs']}u")

    def samples(ss):
        assert len(ss) <= 40
        return ", ".join(f"{{{ms}u, {LEVELS[lv]}}}" for ms, lv in ss)

    lines.append(f"static const led2_key LED2_KEYS[{len(d['keys'])}] = {{")
    for k in d["keys"]:
        lines.append(f"    {{{c_str(k['name'])}, {STATES[k['state']]}, {int(k['selected'])}, {int(k['stale'])}, "
                     f"{len(k['samples'])}, {{{samples(k['samples'])}}}}},")
    lines.append("};")
    lines.append(f"static const led2_button LED2_BUTTONS[{len(d['buttons'])}] = {{")
    for b in d["buttons"]:
        lines.append(f"    {{{c_str(b['name'])}, {len(b['samples'])}, {{{samples(b['samples'])}}}}},")
    lines.append("};")
    ch = d.get("chosen", [])                    # protocol 6 (docs/ui-v3.md section 10.8): the CHOSEN timeline per state
    lines.append(f"static const led2_key LED2_CHOSEN[{max(1, len(ch))}] = {{")
    for k in ch:
        lines.append(f"    {{{c_str(k['name'])}, {STATES[k['state']]}, 0, 0, {len(k['samples'])}, {{{samples(k['samples'])}}}}},")
    if not ch:
        lines.append('    {"none", 0, 0, 0, 0, {{0u, 0}}},')
    lines.append("};")
    lines.append(f"#define LED2_N_CHOSEN {len(ch)}u")
    # the button matrix (docs/ui-v3.md section 9.9, active controls): view x voice x SET_DETAIL.state -> 14 levels per time
    bm = d.get("buttonMatrix", {"times": [0], "buttons": [], "rows": []})
    nt = len(bm["times"])
    lines.append(f"#define LED2_BM_NT {nt}u")
    lines.append(f"static const uint32_t LED2_BM_TIMES[{nt}] = {{{', '.join(f'{t}u' for t in bm['times'])}}};")
    lines.append(f"static const char *const LED2_BM_BUTTONS = {c_str(','.join(bm['buttons']))};")
    lines.append("typedef struct { uint8_t view, voice, dstate; const char *levels[%d]; } led2_brow;" % nt)
    rows = bm["rows"]
    lines.append(f"static const led2_brow LED2_BM[{max(1, len(rows))}] = {{")
    for r in rows:
        lines.append(f"    {{{VIEWS[r['view']]}, {VOICES[r['voice']]}, {STATES[r['dstate']]}, "
                     f"{{{', '.join(c_str(x) for x in r['levels'])}}}}},")
    if not rows:
        lines.append("    {0, 0, 0, {0}},")
    lines.append("};")
    lines.append(f"#define LED2_N_BM {len(rows)}u")
    open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
