"""firmware/assets/sprites/*.png -> firmware/firmware/src/fm1c_sprites.h (docs/ui-v3.md section 6.2).

  python3 -I tools/gen_sprites.py [OUT.h]        (from firmware/; default firmware/src/fm1c_sprites.h)

Sources: hero-<pose>-<provider>.png (24 px high, one 24 x 24 frame per 24 px of width) and mini-<pose>-<provider>.png
(12 px high, 12 x 12 frames), palette mode, every pixel an index of the 16-entry sprite palette (0 transparent,
1-12 fixed colours, 13-15 the state's body, light and shade). Checks the sizes, the frame counts against the
animation table below, that indices 1-12 carry the fixed colours, and that every pixel is in 0..15. Output: raw 4 bpp,
2 pixels per byte, high nibble first, rows top to bottom; frames random-access with no decoder. The output is
deterministic: tests/console/run.sh regenerates it and requires the committed header to be byte-equal."""
import sys
from pathlib import Path

from PIL import Image

FW = Path(__file__).resolve().parent.parent
SRC = FW / "assets" / "sprites"
DEFAULT_OUT = FW / "firmware" / "src" / "fm1c_sprites.h"

POSES = ["work", "wave", "hand", "dizzy", "happy", "sleep", "huh", "ghost"]
PROVIDERS = ["claude", "codex"]
# pose -> (hero frames, hero fps, mini frames, mini fps); a mini with fps 0 is static (calm states)
ANIM = {"work": (4, 8, 2, 4), "wave": (4, 6, 2, 4), "hand": (4, 6, 2, 4), "dizzy": (4, 6, 2, 4), "happy": (4, 8, 2, 4),
        "sleep": (4, 4, 1, 0), "huh": (4, 4, 1, 0), "ghost": (2, 4, 1, 0)}
# FM1C_S_* order (fm1c_proto.h): state -> pose ("" none), body colour. Four slot colours too dark to carry a face
# on black are lightened for sprites only (docs/ui-v3.md section 2).
STATES = [("empty", "", (0, 0, 0)), ("disconnected", "ghost", (56, 56, 56)), ("idle", "sleep", (112, 112, 112)),
          ("working", "work", (47, 125, 246)), ("waiting_input", "wave", (160, 80, 240)),
          ("approval_required", "hand", (255, 176, 0)), ("completed_unread", "happy", (32, 192, 96)),
          ("completed_read", "sleep", (60, 122, 80)), ("failed", "dizzy", (240, 48, 48)),
          ("unknown", "huh", (84, 84, 84))]
BASE = {1: (16, 20, 24), 2: (255, 255, 255), 3: (255, 120, 150), 4: (255, 220, 60), 5: (184, 192, 204),
        6: (110, 118, 130), 7: (16, 28, 52), 8: (110, 190, 255), 9: (90, 90, 90), 10: (150, 150, 150),
        11: (255, 150, 170), 12: (0, 0, 0)}
NOTES = ["F3", "F#3", "G3", "G#3", "A3", "A#3", "B3", "C4", "C#4", "D4", "D#4", "E4", "F4", "F#4", "G4", "G#4", "A4",
         "A#4", "B4", "C5", "C#5", "D5", "D#5", "E5", "F5", "F#5", "G5"]


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def shades(body):
    light = tuple(min(255, int(v + (255 - v) * 0.45)) for v in body)
    shade = tuple(int(v * 0.62) for v in body)
    return body, light, shade


def load(kind, pose, prov, n, frames):
    path = SRC / f"{kind}-{pose}-{prov}.png"
    im = Image.open(path)
    if im.mode != "P":
        raise SystemExit(f"{path.name}: palette mode required, got {im.mode}")
    if im.size != (n * frames, n):
        raise SystemExit(f"{path.name}: {im.size[0]} x {im.size[1]}, want {n * frames} x {n} ({frames} frames)")
    pal = im.getpalette()[:48]
    for i, c in BASE.items():
        if tuple(pal[3 * i:3 * i + 3]) != c:
            raise SystemExit(f"{path.name}: palette entry {i} is {tuple(pal[3 * i:3 * i + 3])}, want {c}")
    px = list(im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata())
    bad = [v for v in px if v > 15]
    if bad:
        raise SystemExit(f"{path.name}: pixel index {bad[0]} outside the 16-entry sprite palette")
    out = []
    for f in range(frames):
        rows = [[px[y * n * frames + f * n + x] for x in range(n)] for y in range(n)]
        out.append(bytes((r[x] << 4) | r[x + 1] for r in rows for x in range(0, n, 2)))
    return out


def arr(name, frames, per):
    lines = [f"static const uint8_t {name}[{len(frames)}][{per}] = {{"]
    for i, fr in enumerate(frames):
        lines.append(f"    {{ /* {i} */")
        for o in range(0, len(fr), 24):
            lines.append("        " + ", ".join(f"0x{b:02x}" for b in fr[o:o + 24]) + ",")
        lines.append("    },")
    lines.append("};")
    return lines


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    hero, mini, hero_at, mini_at = [], [], [], []
    for pose in POSES:
        hf, _, mf, _ = ANIM[pose]
        ha, ma = [], []
        for prov in PROVIDERS:
            ha.append(len(hero))
            hero += load("hero", pose, prov, 24, hf)
            ma.append(len(mini))
            mini += load("mini", pose, prov, 12, mf)
        hero_at.append(ha)
        mini_at.append(ma)
    L = [
        "/* SPDX-License-Identifier: GPL-3.0-only */",
        "/* GENERATED by tools/gen_sprites.py from the PNGs in assets/sprites: do not edit (edit the PNGs, run it again).",
        " * The state characters of docs/ui-v3.md section 2: Claude a round cat-blob, Codex a boxy bot; 24 x 24 hero frames",
        " * (drawn 2x: 48 x 48) and 12 x 12 minis, 4 bpp (2 pixels per byte, high nibble first), index 0 transparent,",
        " * 1-12 FM1C_SPR_PAL_BASE, 13-15 the state's body / light / shade (FM1C_SPR_PAL_STATE). Pure data on <stdint.h>. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define FM1C_SPR_POSES {len(POSES)}u",
        "#define FM1C_SPR_NONE 0xFFu                     /* no character (an empty slot) */",
        "#define FM1C_SPR_HERO_N 24u",
        "#define FM1C_SPR_MINI_N 12u",
        "#define FM1C_SPR_HERO_BYTES 288u",
        "#define FM1C_SPR_MINI_BYTES 72u",
        f"#define FM1C_SPR_HERO_FRAMES {len(hero)}u",
        f"#define FM1C_SPR_MINI_FRAMES {len(mini)}u",
        "enum { " + ", ".join(f"FM1C_POSE_{p.upper()} = {i}" for i, p in enumerate(POSES)) + " };",
        "",
        "/* pose -> hero frames, hero fps, mini frames, mini fps (0: a still mini) */",
        "static const uint8_t FM1C_SPR_ANIM[FM1C_SPR_POSES][4] = {",
        *[f"    {{{a[0]}, {a[1]}, {a[2]}, {a[3]}}},   /* {p} */" for p, a in ((p, ANIM[p]) for p in POSES)],
        "};",
        "/* FM1C_S_* -> pose */",
        "static const uint8_t FM1C_SPR_POSE_OF_STATE[10] = {"
        + ", ".join("FM1C_SPR_NONE" if not s[1] else f"FM1C_POSE_{s[1].upper()}" for s in STATES) + "};",
        "/* [pose][0 claude, 1 codex] -> the first frame in FM1C_SPR_HERO / FM1C_SPR_MINI */",
        "static const uint8_t FM1C_SPR_HERO_AT[FM1C_SPR_POSES][2] = {"
        + ", ".join(f"{{{a}, {b}}}" for a, b in hero_at) + "};",
        "static const uint8_t FM1C_SPR_MINI_AT[FM1C_SPR_POSES][2] = {"
        + ", ".join(f"{{{a}, {b}}}" for a, b in mini_at) + "};",
        "/* RGB565: index 0 (transparent, unused) and the fixed colours 1-12 */",
        "static const uint16_t FM1C_SPR_PAL_BASE[13] = {"
        + ", ".join(["0x0000"] + [f"0x{rgb565(BASE[i]):04x}" for i in range(1, 13)]) + "};",
        "/* FM1C_S_* -> body, light, shade (RGB565) */",
        "static const uint16_t FM1C_SPR_PAL_STATE[10][3] = {",
        *[f"    {{0x{rgb565(b):04x}, 0x{rgb565(l):04x}, 0x{rgb565(s):04x}}},   /* {name} */"
          for name, _, body in STATES for (b, l, s) in [shades(body)]],
        "};",
        "/* the physical key of each slot (docs/firmware-controls.md): F3 .. G5 */",
        "static const char FM1C_NOTE[27][4] = {" + ", ".join(f'"{n}"' for n in NOTES) + "};",
        "",
        *arr("FM1C_SPR_HERO", hero, 288),
        "",
        *arr("FM1C_SPR_MINI", mini, 72),
        "",
    ]
    text = "\n".join(L)
    out.write_text(text)
    print(f"{out}: {len(hero)} hero frames ({len(hero) * 288} B), {len(mini)} mini frames ({len(mini) * 72} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
