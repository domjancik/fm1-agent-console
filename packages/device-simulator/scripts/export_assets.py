"""Exports the firmware's pixels for the simulator's version 4 renderer (docs/ui-v3.md section 6.4).

Writes packages/device-simulator/src/assets/fm1-v4.json:
  fonts    FONT_S and FONT_L from firmware/firmware/gen/felucca_font.h (4-bit alpha glyphs, as gfx.c cv_text draws them)
  sprites  every pose x provider: 24x24 hero frames and 12x12 mini frames, 4 bpp, 2 pixels per byte, high nibble first
           (the fm1c_sprites.h layout), the base palette and the 3 body shades per state, all RGB565

Sprite source, first found wins (so the simulator follows the firmware once the firmware has its own copy):
  1. firmware/firmware/src/fm1c_sprites.h          (generated by tools/gen_sprites.py, docs/ui-v3.md section 6.2)
  2. reports/evidence/ui-v3/scripts/sprites.py     (the procedural first pass the mocks are drawn from)

Run: python3 -I packages/device-simulator/scripts/export_assets.py [--check]
--check exits 1 when the committed JSON differs from a fresh export (used by test/v4-screen.test.ts).
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
FONT_H = os.path.join(REPO, "firmware", "firmware", "gen", "felucca_font.h")
SPRITES_H = os.path.join(REPO, "firmware", "firmware", "src", "fm1c_sprites.h")
SPRITES_PY = os.path.join(REPO, "reports", "evidence", "ui-v3", "scripts")
OUT = os.path.join(HERE, "..", "src", "assets", "fm1-v4.json")

POSES = ["work", "wave", "hand", "dizzy", "happy", "sleep", "huh", "ghost"]
PROVIDERS = ["claude", "codex"]
# protocol state enum order (docs/protocol.md section 4)
STATES = ["empty", "disconnected", "idle", "working", "waiting_input", "approval_required", "completed_unread",
          "completed_read", "failed", "unknown"]


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def arr(src, name):
    m = re.search(r"%s\[\d*\]\s*=\s*\{([^}]*)\}" % re.escape(name), src)
    if not m:
        raise SystemExit("%s not found" % name)
    return [int(v, 0) for v in m.group(1).replace("\n", " ").split(",") if v.strip()]


def font(src, prefix):
    m = re.search(r"felucca_font_t %s = \{ (\d+), (\d+), (\d+), (\d+)" % prefix, src)
    h, pad, first, last = map(int, m.groups())
    return {"h": h, "pad": pad, "first": first, "last": last, "off": arr(src, prefix + "_OFF"),
            "adv": arr(src, prefix + "_ADV"), "bw": arr(src, prefix + "_BW"),
            "data": bytes(arr(src, prefix + "_DATA")).hex()}


def pack4(grid):
    flat = [v for row in grid for v in row]
    return bytes((flat[i] << 4) | flat[i + 1] for i in range(0, len(flat), 2)).hex()


def from_procedural():
    sys.path.insert(0, SPRITES_PY)
    import sprites as sp  # noqa: E402  (repo-local throwaway generator)
    hero = {p: {v: [pack4(sp.hero(p, v, f)) for f in range(sp.HERO_ANIM[p][0])] for v in PROVIDERS} for p in POSES}
    mini = {p: {v: [pack4(sp.mini(p, v, f)) for f in range(max(1, sp.MINI_ANIM[p][0]))] for v in PROVIDERS} for p in POSES}
    base = [0] * 16
    for i, c in sp.BASE_PAL.items():
        base[i] = rgb565(c)
    state_pal, pose_of = {}, {}
    for st in STATES:
        if st == "empty":
            continue
        pal = sp.state_pal(st)
        state_pal[st] = [rgb565(pal[13]), rgb565(pal[14]), rgb565(pal[15])]
        pose_of[st] = sp.STATES[st][0]
    anim = {p: {"heroFrames": sp.HERO_ANIM[p][0], "heroFps": sp.HERO_ANIM[p][1],
                "miniFrames": max(1, sp.MINI_ANIM[p][0]), "miniFps": sp.MINI_ANIM[p][1]} for p in POSES}
    return {"source": "reports/evidence/ui-v3/scripts/sprites.py", "hero": hero, "mini": mini, "basePal": base,
            "statePal": state_pal, "poseOfState": pose_of, "anim": anim}


def table(src, name):
    """Every value of `NAME[..][..] = { ... };` in order, comments stripped; enum names are resolved."""
    m = re.search(r"\b%s\s*(\[[^\]]*\])+\s*=\s*\{" % re.escape(name), src)
    if not m:
        raise SystemExit("%s not found in fm1c_sprites.h" % name)
    end = src.index("};", m.end())
    body = re.sub(r"/\*.*?\*/", "", src[m.end():end], flags=re.S)
    names = {"FM1C_SPR_NONE": 0xFF}
    names.update({"FM1C_POSE_%s" % p.upper(): i for i, p in enumerate(POSES)})
    out = []
    for tok in re.findall(r"0x[0-9a-fA-F]+|\d+|[A-Z_][A-Z0-9_]*", body):
        out.append(names[tok] if tok in names else int(tok, 0))
    return out


def from_header():
    """fm1c_sprites.h (firmware/tools/gen_sprites.py): flat frame tables indexed by FM1C_SPR_HERO_AT / _MINI_AT."""
    src = open(SPRITES_H).read()
    hero_flat, mini_flat = table(src, "FM1C_SPR_HERO"), table(src, "FM1C_SPR_MINI")
    anim_flat, pose_of_flat = table(src, "FM1C_SPR_ANIM"), table(src, "FM1C_SPR_POSE_OF_STATE")
    hero_at, mini_at = table(src, "FM1C_SPR_HERO_AT"), table(src, "FM1C_SPR_MINI_AT")
    base, pal = table(src, "FM1C_SPR_PAL_BASE"), table(src, "FM1C_SPR_PAL_STATE")
    anim, hero, mini = {}, {}, {}
    for i, p in enumerate(POSES):
        hf, hfps, mf, mfps = anim_flat[i * 4:i * 4 + 4]
        anim[p] = {"heroFrames": hf, "heroFps": hfps, "miniFrames": max(1, mf), "miniFps": mfps}
        hero[p], mini[p] = {}, {}
        for j, v in enumerate(PROVIDERS):
            h0, m0 = hero_at[i * 2 + j], mini_at[i * 2 + j]
            hero[p][v] = [bytes(hero_flat[(h0 + f) * 288:(h0 + f + 1) * 288]).hex() for f in range(hf)]
            mini[p][v] = [bytes(mini_flat[(m0 + f) * 72:(m0 + f + 1) * 72]).hex() for f in range(max(1, mf))]
    base16 = (base[:13] + [0] * 16)[:16]  # entries 0-12; 13-15 are the per-state body shades
    state_pal = {st: pal[k * 3:k * 3 + 3] for k, st in enumerate(STATES) if st != "empty"}
    pose_of = {st: POSES[pose_of_flat[k]] for k, st in enumerate(STATES) if st != "empty"}
    return {"source": "firmware/firmware/src/fm1c_sprites.h", "hero": hero, "mini": mini, "basePal": base16,
            "statePal": state_pal, "poseOfState": pose_of, "anim": anim}


def export():
    src = open(FONT_H).read()
    sprites = from_header() if os.path.exists(SPRITES_H) else from_procedural()
    doc = {"generatedBy": "packages/device-simulator/scripts/export_assets.py",
           "fonts": {"S": font(src, "FONT_S"), "L": font(src, "FONT_L")}, "sprites": sprites}
    return json.dumps(doc, separators=(",", ":"), sort_keys=True) + "\n"


def main():
    text = export()
    if "--check" in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ""
        if old != text:
            print("fm1-v4.json is stale: run python3 -I packages/device-simulator/scripts/export_assets.py")
            sys.exit(1)
        print("fm1-v4.json is current")
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (os.path.relpath(OUT, REPO), len(text)))


if __name__ == "__main__":
    main()
