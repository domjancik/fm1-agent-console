import type { AsrEngine } from "./asr/engine";
import { SherpaParakeetEngine } from "./asr/sherpa-engine";
import { loadFixtures, wordErrorRate, type AudioFixture } from "./fixtures";
import { transcribeFile } from "./pipeline";

export interface BenchRow {
  file: string;
  run: number;
  asrMs: number;
  totalMs: number;
  wer: number;
  exact: boolean;
  text: string;
  rejected?: string;
}

export interface EngineBench {
  engine: string;
  loadMs: number;
  rssMb?: number;
  rows: BenchRow[];
}

export async function benchEngine(engine: AsrEngine, fixtures: AudioFixture[], runs: number): Promise<EngineBench> {
  const load = await engine.load();
  const rows: BenchRow[] = [];
  for (const fx of fixtures) {
    for (let run = 1; run <= runs; run++) {
      const r = await transcribeFile(fx.path, { engine });
      rows.push({
        file: fx.file,
        run,
        asrMs: r.timings.asrMs,
        totalMs: Math.round(r.timings.totalMs),
        wer: wordErrorRate(fx.expected, r.text),
        exact: r.text === fx.expected,
        text: r.text,
        rejected: r.rejected,
      });
    }
  }
  const rssBytes = engine instanceof SherpaParakeetEngine ? engine.lastStats?.rssBytes : undefined;
  return { engine: engine.id, loadMs: load.ms, rssMb: rssBytes ? Math.round(rssBytes / 1e6) : undefined, rows };
}

export function renderBenchMarkdown(results: EngineBench[], meta: { date: string; host: string; mainRssMb: number }): string {
  const lines = [
    "# ASR benchmark",
    "",
    `Generated by \`bun packages/speech/src/cli.ts bench\` on ${meta.date} (${meta.host}).`,
    "Fixtures: `fixtures/audio` (macOS `say`, clean TTS, so accuracy is optimistic versus a real microphone).",
    "Timings include the silence gate and post-processing; `asr` is recognition only. WER is computed after post-processing against `expected.json`.",
    `Companion (main process) RSS after the run: ${meta.mainRssMb} MB.`,
    "",
  ];
  for (const r of results) {
    const speech = r.rows.filter((row) => !row.rejected);
    const warm = speech.filter((row) => row.run > 1);
    const avg = (xs: number[]): number => (xs.length ? Math.round(xs.reduce((a, b) => a + b, 0) / xs.length) : 0);
    const meanWer = speech.length ? speech.reduce((a, row) => a + row.wer, 0) / speech.length : 0;
    lines.push(
      `## ${r.engine}`,
      "",
      `- Load: ${r.loadMs} ms${r.rssMb !== undefined ? `; worker RSS after the run: ${r.rssMb} MB` : ""}`,
      `- First-run ASR (mean): ${avg(speech.filter((row) => row.run === 1).map((row) => row.asrMs))} ms; warm ASR (mean): ${warm.length ? `${avg(warm.map((row) => row.asrMs))} ms` : "n/a"}`,
      `- Mean WER: ${(meanWer * 100).toFixed(1)}%; exact matches: ${speech.filter((row) => row.exact).length}/${speech.length}`,
      "",
      "| Fixture | Run | ASR ms | Total ms | WER | Exact | Text |",
      "| --- | --- | --- | --- | --- | --- | --- |",
      ...r.rows.map(
        (row) =>
          `| ${row.file} | ${row.run} | ${row.asrMs} | ${row.totalMs} | ${(row.wer * 100).toFixed(1)}% | ${row.exact ? "yes" : "no"} | ${row.rejected ? `_rejected: ${row.rejected}_` : row.text.replace(/\|/g, "\\|")} |`,
      ),
      "",
    );
  }
  return lines.join("\n");
}

