// reports/e2e.md for the simulated acceptance run, with timings against spec section 13.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO_ROOT } from "../context";
import type { Versions } from "../record";
import type { FlowResult } from "./flow";

export interface E2eReportInput {
  results: FlowResult[];
  attachMs: number | null;
  evidenceDir: string;
  json: string;
  versions: Versions;
  companionExit: number | null;
}

const ms = (v: number | null | undefined): string => (v === null || v === undefined ? "n/a" : `${v} ms`);
const cell = (s: string): string => s.replace(/\|/g, "\\|");

/** Spec 13 rows: metric, target, how measured, value per provider. */
function timingRows(results: FlowResult[], attachMs: number | null): string[] {
  const col = (f: (r: FlowResult) => string): string => results.map(f).join(" / ");
  const t = (r: FlowResult, k: string): number | null => r.timings[k] ?? null;
  const linkPart = (r: FlowResult): string => {
    const raw = t(r, "key_press_to_selected_ms");
    return raw === null ? "n/a" : `${raw - 340} ms`;
  };
  return [
    `| Selection-to-display update | < 150 ms | key down → selected flag on the simulator screen, minus the 40 ms tap and the 300 ms double-press window the firmware waits before it sends \`single\` | ${col(linkPart)} (raw ${col((r) => ms(t(r, "key_press_to_selected_ms")))}) |`,
    `| Physical button feedback | < 100 ms | REC down → simulator shows RECORDING (host round trip: BUTTON frame → SET_VOICE) | ${col((r) => ms(t(r, "rec_down_to_recording_ms")))} |`,
    `| Recording start feedback | < 200 ms | same measurement as above | ${col((r) => ms(t(r, "rec_down_to_recording_ms")))} |`,
    `| Short utterance transcription | < 2 s after release | REC up → simulator shows REVIEW with the transcript (Parakeet int8, model warmed at start, 7.15 s fixture) | ${col((r) => ms(t(r, "rec_release_to_transcript_ms")))} |`,
    `| SAVE → backend acknowledged | (no target; stages must be distinct) | SAVE down → simulator shows DELIVERED with result \`acknowledged\` (Traycer \`messageAccepted\`) | ${col((r) => ms(t(r, "save_to_backend_ack_ms")))} |`,
    `| Focus command | (none) | double press → COMMAND_RESULT on the simulator (\`open -a Traycer\`) | ${col((r) => ms(t(r, "double_press_to_focus_result_ms")))} |`,
    `| Device link up | < 5 s reconnect | companion process start → simulator linked with slots drawn (includes Traycer connect and first full listing) | ${ms(attachMs)} |`,
  ];
}

export function writeE2eReport(input: E2eReportInput): string {
  const { results } = input;
  const lines: string[] = [
    "# End-to-end acceptance (simulated FM-1, live Traycer)",
    "",
    `Generated by \`bun tools/smoke-traycer/src/e2e.ts --live\` at ${new Date().toISOString()}. Traycer CLI ${input.versions.cli}, host ${input.versions.host}. Evidence: \`${input.evidenceDir}/\` (\`${input.json}\`).`,
    "",
    "Chain under test (priority update acceptance): FM-1 simulator → select Traycer chat → desktop focus → dictated text submitted to that same chat.",
    "",
    "Setup: the device simulator (`SimDevice` + its browser UI) runs on the CoreMIDI virtual port `FM1 CONSOLE (sim)`. The companion runs as its own process, `fm1-console start --sim --adapter traycer --fixture-audio fixtures/audio/smoke-16k.wav --warm`, with a fresh default config. It found the port by exact name, exactly as it finds a real FM-1. The script drives only simulated controls (`ScriptedDriver`: key presses, REC hold, SAVE) with no mouse. It reads the simulator's screen state and the companion's `/api/state` to check each step. Delivery is checked against `agent.getTranscript`. The microphone is never opened (`FixtureCapture`), nothing is sent to the plugged-in FM-1, and no SysEx is used.",
    "",
    `Result: **${results.filter((r) => r.ok).length}/${results.length} providers passed every step.** Companion exit code after SIGINT: ${input.companionExit ?? "killed"}.`,
    "",
  ];
  for (const r of results) {
    lines.push(`## ${r.provider} chat \`${r.chatId.slice(0, 8)}…\` (${r.ok ? "PASS" : "FAIL"})`, "", "| Step | Result | Detail |", "|---|---|---|");
    for (const s of r.steps) lines.push(`| ${s.step} | ${s.ok ? "ok" : "FAIL"} | ${cell(s.detail)} |`);
    lines.push("", `Focus level reached: **${r.focusLevel}**. Evidence: ${r.evidence.map((e) => `\`${e}\``).join(", ")}`, "");
  }
  lines.push(
    "## Timings against spec section 13",
    "",
    `Values are ${results.map((r) => r.provider).join(" / ")}. One run each, so there is no variance figure. Repeat the script to get a spread.`,
    "",
    "| Metric | Target | Measured as | Value |",
    "|---|---|---|---|",
    ...timingRows(results, input.attachMs),
    "",
  );
  const path = join(REPO_ROOT, "reports", "e2e.md");
  writeFileSync(path, `${lines.join("\n")}\n`);
  return "reports/e2e.md";
}
